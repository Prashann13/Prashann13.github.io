export function drawSprite(ctx, sprite, x, y, colors, facing = 1) {
  const palette = ['', colors.cloak, colors.face, colors.accent, colors.ink, colors.steel, colors.highlight, colors.shadow];
  for (let row = 0; row < sprite.length; row++) for (let col = 0; col < sprite[row].length; col++) {
    const value = Number(sprite[row][col]); if (!value) continue;
    ctx.fillStyle = palette[value];
    ctx.fillRect(Math.round(x) + (facing > 0 ? col : sprite[row].length - 1 - col) * 2, Math.round(y) + row * 2, 2, 2);
  }
}
